-- IAM persistence only. No users, credentials or cross-context schema changes.
CREATE TABLE public.businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_businesses_id CHECK (id > 0),
    CONSTRAINT ck_businesses_name CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
    CONSTRAINT ck_businesses_address CHECK (char_length(btrim(address)) BETWEEN 1 AND 255),
    CONSTRAINT ck_businesses_phone CHECK (char_length(btrim(phone)) BETWEEN 1 AND 32)
);

CREATE TABLE public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(512) NOT NULL,
    user_role VARCHAR(16) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_users_id CHECK (id > 0),
    CONSTRAINT fk_users_business FOREIGN KEY (business_id)
        REFERENCES public.businesses(id) ON DELETE RESTRICT,
    CONSTRAINT ck_users_full_name CHECK (char_length(btrim(full_name)) BETWEEN 1 AND 150),
    CONSTRAINT ck_users_email_normalized CHECK (
        char_length(email) BETWEEN 3 AND 254 AND email = lower(btrim(email))
    ),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_password_hash CHECK (char_length(btrim(password_hash)) > 0),
    CONSTRAINT ck_users_role CHECK (user_role IN ('ADMIN', 'EMPLOYEE'))
);

CREATE INDEX ix_users_business_id ON public.users (business_id);
